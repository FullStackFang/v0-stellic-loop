// Fresh fixture required. Use the connected Playwright tool as described in the report.
export default async function run(page) {
  page.setDefaultTimeout(60000);
  const checks=[],assert=(value,label)=>{if(!value)throw new Error(label);checks.push(label);};
  await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:4319');
  await page.getByRole('heading',{name:'Private preferences',exact:true}).waitFor();
  const state=async(actor='memberA')=>page.evaluate(async actor=>{const response=await fetch(`/__fixture/state?actor=${actor}`);return {status:response.status,body:await response.json()};},actor);
  const capability=(await state()).body.capability;
  const request=async(action,entries,actor='memberA')=>page.evaluate(async({action,entries,actor,capability})=>{
    const response=await fetch(`/__fixture/action?actor=${actor}`,{method:'POST',headers:{'Content-Type':'application/json','X-Rehearsal-Capability':capability},body:JSON.stringify({action,entries})});return response.json();
  },{action,entries,actor,capability});
  const proposal=page.locator('#proposals');
  const review=async(candidate,outcome)=>{
    await proposal.getByLabel('Structured want proposal (JSON)',{exact:true}).fill(JSON.stringify(candidate));
    await proposal.getByRole('button',{name:'Review proposed want',exact:true}).click();
    await proposal.getByText(`Result: ${outcome}`,{exact:true}).waitFor();
  };
  const accept=async()=>{await proposal.getByRole('checkbox').check();await proposal.getByRole('button',{name:'Accept this want',exact:true}).click();};
  const selectActor=async actor=>{await page.getByLabel('Synthetic actor').selectOption(actor);await page.getByRole('heading',{name:'Private preferences',exact:true}).waitFor();};
  const candidate={kind:'want',text:'PROPOSAL_BROWSER_PRIVATE_A',category:'rest',place:'Hanoi',strength:0.6,confidence:0.7,orgId:null,loopId:null};
  await review(candidate,'new');
  assert(!(await state()).body.memory.items.some(m=>m.text===candidate.text),'Proposal review does not persist an active want');
  await proposal.getByRole('button',{name:'Accept this want',exact:true}).click();
  assert(!(await state()).body.memory.items.some(m=>m.text===candidate.text),'Unchecked review blocks browser acceptance');
  await accept();await proposal.getByText('Accepted and saved as your active want.',{exact:true}).waitFor();
  const saved=(await state()).body.memory.items.find(m=>m.text===candidate.text);
  assert(saved?.version===1,'Explicit proposal acceptance creates version 1');
  const conflicting={...candidate,id:saved.id,expectedVersion:1,text:'OLDER_INFERRED_PROPOSAL_A'};
  await review(conflicting,'conflict');
  assert(await proposal.getByRole('heading',{name:'Your current want',exact:true}).count()===1,'Conflicting proposal displays the current want alongside proposed fields');
  const correction={operationId:crypto.randomUUID(),id:saved.id,expectedVersion:'1',kind:'want',text:'EXPLICIT_CORRECTION_WINS_A',category:'rest',place:'Hanoi',strength:'0.9',status:'active'};
  const concurrent=await request('savePreference',Object.entries(correction));
  assert(concurrent.status==='success','Concurrent explicit correction saved through the actual portal action');
  await accept();await proposal.getByRole('alert').filter({hasText:'changed or is unavailable'}).waitFor();
  assert((await state()).body.memory.items.find(m=>m.id===saved.id).text===correction.text,'Stale acceptance cannot overwrite the explicit correction');
  await review(conflicting,'stale');
  assert(await proposal.getByRole('button',{name:'Accept this want',exact:true}).count()===0,'Stale proposal review removes the accept control');
  await page.locator('li').filter({hasText:correction.text}).getByRole('button',{name:'Correct preference'}).click();
  await page.getByRole('combobox',{name:'Status',exact:true}).selectOption('archived');
  await page.getByRole('button',{name:'Save correction',exact:true}).click();
  await page.waitForFunction(async id=>{const s=await(await fetch('/__fixture/state?actor=memberA')).json();return s.memory.items.find(m=>m.id===id)?.status==='archived';},saved.id,{timeout:60000});
  const archived=(await state()).body.memory.items.find(m=>m.id===saved.id);
  await review({...candidate,id:saved.id,expectedVersion:archived.version,text:archived.text,strength:archived.strength,confidence:archived.confidence},'conflict');
  await accept();await proposal.getByText('Accepted and saved as your active want.',{exact:true}).waitFor();
  assert((await state()).body.memory.items.find(m=>m.id===saved.id).status==='active','Archived want reactivation requires explicit conflict review and acceptance');
  await selectActor('memberB');
  await review({...candidate,id:saved.id,expectedVersion:4},'stale');
  assert(await proposal.getByRole('heading',{name:'Your current want',exact:true}).count()===0,'Other member review cannot retrieve the target owner current want');
  await page.getByLabel('Preference',{exact:true}).fill('MEMBER_B_EXPORT_CANARY');
  await page.getByRole('button',{name:'Save private preference',exact:true}).click();
  await page.locator('li').filter({hasText:'MEMBER_B_EXPORT_CANARY'}).waitFor();
  await selectActor('memberA');
  const privacy=page.locator('#privacy');
  await privacy.getByRole('button',{name:'Prepare my data export',exact:true}).click();
  await privacy.getByRole('alert').waitFor();
  assert(await privacy.getByRole('button',{name:'Download my pilot data',exact:true}).count()===0,'Export without fresh authentication offers no download');
  await page.getByRole('button',{name:'Refresh synthetic authentication',exact:true}).click();
  await page.getByTestId('rehearsal-result').filter({hasText:'Synthetic authentication refreshed.'}).waitFor();
  await privacy.getByRole('button',{name:'Prepare my data export',exact:true}).click();
  await privacy.getByRole('button',{name:'Download my pilot data',exact:true}).waitFor();
  const downloading=page.waitForEvent('download');await privacy.getByRole('button',{name:'Download my pilot data',exact:true}).click();
  const download=await downloading,stream=await download.createReadStream();let contents='';for await(const chunk of stream)contents+=chunk.toString();
  const exported=JSON.parse(contents);
  assert(exported.scope==='emba-pilot'&&contents.includes('EXPLICIT_CORRECTION_WINS_A'),'Fresh-authenticated browser download contains the member own data');
  assert(!contents.includes('MEMBER_B_EXPORT_CANARY'),'Downloaded export excludes another member private preference');
  await page.getByRole('button',{name:'Expire synthetic authentication',exact:true}).click();
  await page.getByTestId('rehearsal-result').filter({hasText:'Synthetic authentication expired.'}).waitFor();
  await privacy.getByText('Delete my pilot data',{exact:true}).click();
  await privacy.getByRole('checkbox').check();await privacy.getByRole('button',{name:'Delete pilot data',exact:true}).click();
  await privacy.getByRole('alert').waitFor();
  assert((await state()).status===200,'Expired authentication prevents browser deletion');
  await page.getByRole('button',{name:'Refresh synthetic authentication',exact:true}).click();
  await page.getByTestId('rehearsal-result').filter({hasText:'Synthetic authentication refreshed.'}).waitFor();
  await privacy.getByRole('checkbox').check();await privacy.getByRole('button',{name:'Delete pilot data',exact:true}).click();
  await page.getByRole('heading',{name:'Pilot access unavailable',exact:true}).waitFor();
  assert((await state()).status===403,'Deletion immediately blocks the prior member session');
  assert((await request('exportPilotData',[])).status==='error','Prior first-party principal cannot export after deletion');
  assert((await request('savePreference',Object.entries({...correction,operationId:crypto.randomUUID(),id:saved.id,expectedVersion:'4'}))).status==='error','Prior first-party principal cannot recreate deleted memory');
  await selectActor('memberB');
  assert((await state('memberB')).body.memory.items.some(m=>m.text==='MEMBER_B_EXPORT_CANARY'),'Another member retains their own data after deletion');
  await page.screenshot({path:'.playwright-mcp/emba-browser-proposal-privacy.png',fullPage:true});
  return {checks,scope:'Real components/actions/services; synthetic trusted authentication-age control, not provider reauthentication'};
}
