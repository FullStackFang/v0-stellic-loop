// Fresh disposable fixture required. No invitation tokens are returned in results.
export default async function run(page) {
  page.setDefaultTimeout(60000);
  const checks=[],assert=(value,label)=>{if(!value)throw new Error(label);checks.push(label);};
  await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:4319');
  await page.getByRole('heading',{name:'Private preferences',exact:true}).waitFor();
  const state=async(actor='organizer')=>page.evaluate(async actor=>(await fetch(`/__fixture/state?actor=${actor}`)).json(),actor);
  const capability=(await state()).capability;
  const request=async(path,data,actor='organizer')=>page.evaluate(async({path,data,actor,capability})=>{
    const r=await fetch(`/__fixture/${path}?actor=${actor}`,{method:'POST',headers:{'Content-Type':'application/json','X-Rehearsal-Capability':capability},body:JSON.stringify(data)});return {status:r.status,body:await r.json()};
  },{path,data,actor,capability});
  const selectActor=async actor=>{await page.getByLabel('Synthetic actor').selectOption(actor);await page.getByRole('heading',{name:'Private preferences',exact:true}).waitFor();};
  const invitations=page.locator('#invitations');
  const create=async()=>{
    await invitations.getByLabel('Recipient email',{exact:true}).fill('nonmember@example.test');
    await invitations.getByLabel('Expires at (UTC)',{exact:true}).fill('2098-12-01T12:00');
    await invitations.getByRole('button',{name:'Create invitation',exact:true}).click();
    await invitations.getByText('Invitation created. Share the token privately; email delivery is not configured.',{exact:true}).waitFor();
    return invitations.getByRole('textbox',{name:/^Invitation token \(share privately with the recipient\)/}).inputValue();
  };
  const redeem=async token=>{await invitations.getByLabel('Private invitation token',{exact:true}).fill(token);await invitations.getByRole('button',{name:'Accept invitation',exact:true}).click();};
  await selectActor('organizer');
  let token=await create();
  assert((await state()).invitations.length===1,'Organizer browser form creates a recipient-bound invitation');
  await selectActor('memberA');await redeem(token);await invitations.getByRole('alert').waitFor();
  assert(!(await state()).invitations[0].accepted_at,'Wrong verified recipient cannot accept invitation');
  await selectActor('organizer');
  await invitations.getByRole('button',{name:'Revoke invitation',exact:true}).click();
  await invitations.getByText('nonmember@example.test - Revoked',{exact:true}).waitFor();
  await selectActor('nonmember');await redeem(token);await invitations.getByRole('alert').waitFor();
  assert((await state('nonmember')).loops.length===0,'Revoked invitation cannot enroll its recipient');
  await selectActor('organizer');token=await create();
  const expiring=(await state()).invitations.find(i=>!i.revoked_at);
  if((await request('expire-invitation',{id:expiring.id})).status!==200)throw new Error('Synthetic expiration control failed');
  await selectActor('nonmember');await redeem(token);await invitations.getByRole('alert').waitFor();
  assert((await state('nonmember')).loops.length===0,'Expired invitation cannot enroll its recipient');
  await selectActor('organizer');token=await create();
  await selectActor('nonmember');await redeem(token);
  await page.waitForFunction(async()=>{const s=await(await fetch('/__fixture/state?actor=nonmember')).json();return s.loops.length>0;});
  const invitedLoop=(await state()).scope.loopId;
  assert((await state('nonmember')).loops.some(l=>l.loopId===invitedLoop),'Matching synthetic verified email enrolls in the invited trip');
  await redeem(token);await invitations.getByRole('alert').waitFor();
  assert((await state()).invitations.filter(i=>i.accepted_at).length===1,'Consumed invitation cannot be replayed');
  await selectActor('organizer');
  const upload=page.locator('#upload-resource');
  await upload.getByLabel('Source title',{exact:true}).fill('BROWSER_RESOURCE');
  await upload.getByRole('combobox',{name:'Format',exact:true}).selectOption('application/json');
  await upload.getByLabel('Source content',{exact:true}).fill('{malformed');
  await upload.getByRole('button',{name:'Accept source',exact:true}).click();
  await upload.getByRole('alert').waitFor();
  assert(!(await state()).documents.some(d=>d.title==='BROWSER_RESOURCE'),'Malformed structured source is rejected before persistence');
  await upload.getByLabel('Source title',{exact:true}).fill('BROWSER_RESOURCE');
  await upload.getByRole('combobox',{name:'Format',exact:true}).selectOption('application/json');
  await upload.getByLabel('Source content',{exact:true}).fill(JSON.stringify({itineraryVersion:'browser-v1',timezone:'Asia/Ho_Chi_Minh',passages:[{text:'Hanoi bus browser resource version one.'}]}));
  await upload.getByRole('button',{name:'Accept source',exact:true}).click();
  await page.getByRole('heading',{name:'BROWSER_RESOURCE',exact:true}).waitFor();
  let doc=(await state()).documents.find(d=>d.title==='BROWSER_RESOURCE');
  const row=()=>page.locator(`[data-document-id="${doc.id}"]`);
  assert(doc.state==='accepted','Upload accepts source without prematurely publishing evidence');
  if((await request('fail-processing',{id:doc.id,version:1})).status!==200)throw new Error('Synthetic failed worker control failed');
  await selectActor('memberA');await selectActor('organizer');
  await row().getByRole('button',{name:'Retry processing',exact:true}).waitFor();
  assert(!(await state('memberA')).passages.some(p=>p.documentId===doc.id),'Simulated failed worker state exposes no partial evidence to members');
  await row().getByRole('button',{name:'Retry processing',exact:true}).click();await row().getByText('Version 1 - ready',{exact:true}).waitFor();
  assert((await state('memberA')).passages.some(p=>p.documentId===doc.id),'Actual browser retry processes a failed source into available evidence');
  await row().getByText('Correct this source',{exact:true}).click();
  await row().getByLabel('Source title',{exact:true}).fill('BROWSER_RESOURCE_CORRECTED');
  await row().getByRole('combobox',{name:'Format',exact:true}).selectOption('application/json');
  await row().getByLabel('Source content',{exact:true}).fill(JSON.stringify({itineraryVersion:'browser-v2',timezone:'Asia/Ho_Chi_Minh',passages:[{text:'Hanoi bus BROWSER_CITATION_CANARY leaves at 15:00.'}]}));
  await row().getByRole('button',{name:'Save corrected version',exact:true}).click();
  await page.getByRole('heading',{name:'BROWSER_RESOURCE_CORRECTED',exact:true}).waitFor();
  doc=(await state()).documents.find(d=>d.id===doc.id);
  assert(doc.version===2&&doc.state==='accepted','Correction creates a new unprocessed version');
  const unauthorized=await request('action',{action:'processResource',entries:[['documentId',doc.id],['version','2']]},'memberA');
  assert(unauthorized.body.status==='error','Ordinary member cannot process organizer source');
  await row().getByRole('button',{name:'Process source',exact:true}).click();await row().getByText('Version 2 - ready',{exact:true}).waitFor();
  await selectActor('memberA');
  await page.locator('blockquote').filter({hasText:'Hanoi bus BROWSER_CITATION_CANARY leaves at 15:00.'}).waitFor();
  const passage=(await state('memberA')).passages.find(p=>p.documentId===doc.id);
  assert(passage?.version===2&&passage.timezone==='Asia/Ho_Chi_Minh'&&passage.itineraryVersion==='browser-v2','Member sees processed current source citation and timezone');
  assert(await page.locator('#resources').getByRole('button',{name:'Delete source',exact:true}).count()===0,'Member resource view excludes organizer mutation controls');
  await selectActor('organizer');
  await row().getByRole('button',{name:'Delete source',exact:true}).click();
  assert((await state()).documents.some(d=>d.id===doc.id),'Unchecked deletion confirmation prevents browser submission');
  await row().getByRole('checkbox').check();await row().getByRole('button',{name:'Delete source',exact:true}).click();
  await page.getByRole('heading',{name:'BROWSER_RESOURCE_CORRECTED',exact:true}).waitFor({state:'detached'});
  await selectActor('memberA');
  assert(!(await state('memberA')).passages.some(p=>p.documentId===doc.id),'Deleted source disappears from member evidence');
  assert((await request('read-document',{id:doc.id,version:1},'memberA')).status===403&&(await request('read-document',{id:doc.id,version:2},'memberA')).status===403,'Deleted current and historical source bodies are unavailable');
  await page.screenshot({path:'.playwright-mcp/emba-browser-organizer.png',fullPage:true});
  return {checks,scope:'Real invitation/resource components and actions; synthetic verified email and fixture expiration, no provider flow or email delivery'};
}
