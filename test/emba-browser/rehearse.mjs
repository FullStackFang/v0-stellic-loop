// Run with the connected Playwright browser tool: import this module, then run(page).
// Requires scripts/emba-browser.ts at its fixed loopback address and a fresh fixture.
export default async function run(page) {
  const checks=[];
  const assert=(value,message)=>{if(!value)throw new Error(message);checks.push(message);};
  const origin='http://127.0.0.1:4319';
  const state=async(actor='memberA')=>page.evaluate(async actor=>{const response=await fetch(`/__fixture/state?actor=${actor}`);return response.json();},actor);
  const request=async(path,data={},actor='memberA')=>page.evaluate(async({path,data,actor})=>{
    const state=await (await fetch(`/__fixture/state?actor=${actor}`)).json();
    const response=await fetch(`/__fixture/${path}?actor=${actor}`,{method:'POST',headers:{'Content-Type':'application/json','X-Rehearsal-Capability':state.capability},body:JSON.stringify(data)});
    return {status:response.status,body:await response.json()};
  },{path,data,actor});
  const selectActor=async actor=>{await page.getByLabel('Synthetic actor').selectOption(actor);await page.getByRole('heading',{name:'Private preferences',exact:true}).waitFor();};
  const grant=async(scope,actions)=>{
    await page.getByLabel('Assistant client ID').fill('browser-assistant');
    for(const [label,enabled] of [['Read private preferences',actions.includes('memory:read')],['Read personal plans',actions.includes('plan:read')],['Request activity actions (confirmation required)',actions.includes('activity:write')]])await page.getByLabel(label,{exact:true}).setChecked(enabled);
    await page.getByLabel('Expires at (UTC)',{exact:true}).fill('2098-01-01T12:00');
    await page.getByLabel('Access context').selectOption(scope);
    await page.getByRole('button',{name:'Grant selected access'}).click();
    await page.waitForFunction(async scope=>{const s=await (await fetch('/__fixture/state?actor=memberA')).json();return s.leases.some(l=>!l.revoked_at&&(scope==='personal'?l.loop_id===null:`${l.org_id}:${l.loop_id}`===scope));},scope);
  };
  await page.setViewportSize({width:390,height:844});
  await page.goto(origin);
  await page.getByRole('heading',{name:'Private preferences',exact:true}).waitFor();
  const marker='Keyboard-only browser preference';
  await page.getByLabel('Preference',{exact:true}).focus();
  await page.keyboard.type(marker);
  await page.keyboard.press('Tab');await page.keyboard.press('Tab');await page.keyboard.type('Hanoi');
  await page.keyboard.press('Tab');await page.keyboard.press('ControlOrMeta+A');await page.keyboard.type('0.8');
  await page.keyboard.press('Tab');await page.keyboard.press('Tab');await page.keyboard.press('Enter');
  await page.locator('li').filter({hasText:marker}).waitFor();
  assert((await state()).memory.items.some(m=>m.text===marker&&m.version===1),'Keyboard submit persisted a private preference');
  await page.locator('li').filter({hasText:marker}).getByRole('button',{name:'Correct preference'}).click();
  await page.getByRole('textbox',{name:/^Preference/}).fill(`${marker} corrected`);
  await page.getByRole('button',{name:'Save correction'}).click();
  await page.locator('li').filter({hasText:`${marker} corrected`}).filter({hasText:'Version 2'}).waitFor();
  assert((await state()).memory.items.some(m=>m.text===`${marker} corrected`&&m.version===2),'Correction persisted version 2');
  await selectActor('memberB');
  assert(!(await page.locator('body').innerText()).includes(marker),'Member B cannot see Member A private preference');
  await selectActor('organizer');
  assert(!(await page.locator('body').innerText()).includes(marker),'Organizer cannot see Member A private preference');
  await selectActor('memberA');
  await page.getByRole('button',{name:'Try delegated preference read'}).click();
  await page.getByTestId('rehearsal-result').filter({hasText:'denied'}).waitFor();
  checks.push('Assistant private read denied before consent');
  await grant('personal',['memory:read']);
  await page.getByRole('button',{name:'Try delegated preference read'}).click();
  await page.getByTestId('rehearsal-result').filter({hasText:marker}).waitFor();
  checks.push('Explicit lease permits assistant private read');
  await page.getByRole('button',{name:'Revoke access',exact:true}).click();
  await page.locator('li').filter({hasText:'browser-assistant'}).filter({hasText:'Revoked'}).waitFor();
  await page.getByRole('button',{name:'Try delegated preference read'}).click();
  await page.getByTestId('rehearsal-result').filter({hasText:'denied'}).waitFor();
  checks.push('Revocation blocks subsequent assistant output');
  const s=await state(),scope=`${s.scope.orgId}:${s.scope.loopId}`;
  await grant(scope,['plan:read','activity:write']);
  await page.getByRole('button',{name:'Prepare assistant commitment'}).click();
  await page.getByRole('textbox',{name:/^Prepared binding/}).waitFor();
  let binding=await page.getByRole('textbox',{name:/^Prepared binding/}).inputValue();
  await page.getByLabel('Structured action from your assistant').fill(binding);
  await page.getByRole('button',{name:'Review action',exact:true}).click();
  await page.getByRole('checkbox',{name:'I reviewed the activity, conditions and disclosure above.'}).waitFor();
  await page.getByRole('button',{name:'Advance fixture revision'}).click();
  await page.getByTestId('rehearsal-result').filter({hasText:'Fixture revision advanced.'}).waitFor();
  await page.getByRole('checkbox',{name:'I reviewed the activity, conditions and disclosure above.'}).check();
  await page.getByRole('button',{name:'Approve this exact assistant action'}).click();
  await page.getByRole('alert').filter({hasText:'changed'}).waitFor();
  assert(await page.getByLabel('Confirmation ID',{exact:true}).count()===0,'Stale browser approval requires fresh review');
  await page.getByRole('button',{name:'Prepare assistant commitment'}).click();
  await page.waitForFunction(()=>{const field=document.querySelector('textarea[readonly]');return field&&JSON.parse(field.value).expectedVersion===2;});
  binding=await page.getByRole('textbox',{name:/^Prepared binding/}).inputValue();
  await page.getByLabel('Structured action from your assistant').fill(binding);
  await page.getByRole('button',{name:'Review action',exact:true}).click();
  await page.getByText('Revision: 2',{exact:false}).waitFor();
  await page.getByRole('checkbox',{name:'I reviewed the activity, conditions and disclosure above.'}).check();
  await page.getByRole('button',{name:'Approve this exact assistant action'}).click();
  await page.getByLabel('Confirmation ID',{exact:true}).waitFor();
  const confirmationId=await page.getByLabel('Confirmation ID',{exact:true}).inputValue();
  const execution=await request('execute',{confirmationId,payload:JSON.parse(binding).payload});
  assert(execution.status===200,'Reviewed browser confirmation executes through real action service');
  assert((await state()).activity.ownCommitment.status==='active','Confirmed execution persisted current-revision commitment');
  assert((await request('execute',{confirmationId,payload:JSON.parse(binding).payload})).status===403,'Confirmation replay denied');
  await page.reload();await page.getByRole('button',{name:'Withdraw commitment'}).waitFor();
  await page.getByRole('button',{name:'Withdraw commitment'}).click();
  await page.getByText('Your commitment: withdrawn',{exact:true}).waitFor();
  assert((await state()).activity.ownCommitment.status==='withdrawn','Browser withdrawal persisted without assistant');
  await selectActor('nonmember');
  await page.getByText('No authorized trip evidence.',{exact:true}).waitFor();
  await page.getByText('No authorized activity.',{exact:true}).waitFor();
  await page.getByLabel('Structured action from your assistant').fill(binding);
  await page.getByRole('button',{name:'Review action',exact:true}).click();
  await page.getByRole('alert').waitFor();
  assert(await page.getByRole('button',{name:'Approve this exact assistant action'}).count()===0,'Nonmember denied trip evidence, activity and consequential review');
  await selectActor('memberA');
  for(const width of [320,390,1440]){
    await page.setViewportSize({width,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`No horizontal overflow at ${width}px`);
  }
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'.playwright-mcp/emba-browser-mobile.png',fullPage:true});
  const noOrigin=await page.request.post(`${origin}/__fixture/action?actor=memberA`,{data:{action:'savePreference',entries:[]}});
  assert(noOrigin.status()===403,'Fixture mutation rejects missing Origin/capability');
  const hostile=await page.request.post(`${origin}/__fixture/action?actor=memberA`,{headers:{Origin:'https://attacker.example'},data:{action:'savePreference',entries:[]}});
  assert(hostile.status()===403,'Fixture mutation rejects foreign Origin');
  return {checks,scope:'Synthetic real-component/action/service browser rehearsal; not OAuth or Next transport acceptance'};
}
